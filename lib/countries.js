/** The two-letter code for a country name, or null. Case and accents do not matter. */
export function countryCode(name) {
  const raw = String(name || '').toLowerCase().trim();
  const plain = raw.normalize('NFKD').replace(/\p{M}/gu, '');
  return CODES[raw] || CODES[plain] || null;
}
